import "dotenv/config";
import { chromium } from "playwright";
import sharp from "sharp";
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { eq } from "drizzle-orm";
import { db, schema } from "../src/db/index.js";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const OUT_DIR = path.join(__dirname, "..", "public", "thumbnails");

async function shoot(browser, site) {
  const context = await browser.newContext({ viewport: { width: 1280, height: 800 } });
  const page = await context.newPage();
  const outPath = path.join(OUT_DIR, `${site.slug}.webp`);

  try {
    await page.goto(site.url, { waitUntil: "networkidle", timeout: 15000 });
  } catch {
    // Network never went idle (common on sites with polling/websockets) —
    // fall back to whatever painted so far rather than failing the run.
  }

  const buffer = await page.screenshot({ type: "png" });
  await sharp(buffer)
    .resize(640, 400, { fit: "cover", position: "top" })
    .webp({ quality: 80 })
    .toFile(outPath);

  await context.close();
  return `/thumbnails/${site.slug}.webp`;
}

async function main() {
  await fs.mkdir(OUT_DIR, { recursive: true });

  // Pulls the live site list from the database — this used to import a
  // static SITES array from src/lib/sites.js, but that file has been a
  // pure DB-query module (getAllSites, getSiteBySlug, etc.) for a while
  // now, not a static export, so that import silently resolved to
  // `undefined` and this script has been broken since. Only targets sites
  // with no image yet, or one already generated by this same script
  // (`/thumbnails/<slug>.webp`) — never overwrites a manually-set external
  // image URL someone put in through the admin form.
  const sites = await db.select().from(schema.sites);
  const targets = sites.filter((s) => !s.image || s.image === `/thumbnails/${s.slug}.webp`);

  if (targets.length === 0) {
    console.log("Nothing to do — every site already has a manually-set image.");
    process.exit(0);
  }

  const browser = await chromium.launch();
  for (const site of targets) {
    try {
      const imagePath = await shoot(browser, site);
      await db
        .update(schema.sites)
        .set({ image: imagePath, updatedAt: new Date() })
        .where(eq(schema.sites.id, site.id));
      console.log(`✓ ${site.slug} -> ${imagePath}`);
    } catch (err) {
      console.error(`✗ ${site.slug}: ${err.message}`);
    }
  }
  await browser.close();
  process.exit(0);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
